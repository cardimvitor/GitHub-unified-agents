import { useEffect, useState } from 'react'
import { ActivityIndicator, Pressable, StyleSheet, Text, TextInput, View } from 'react-native'
import { AGENTS_ENVIRONMENT, ensureAgentsEnvironment } from '@/github/environments'
import { setEnvironmentSecret } from '@/github/secrets'
import { agentCredentials } from '@/storage/agent-credentials'
import { agentSettings } from '@/storage/agent-settings'
import { githubSession } from '@/storage/github-session'
import { githubTarget } from '@/storage/github-target'

export default function SetupClaudeSubscription() {
  const [repository, setRepository] = useState('')
  const [token, setToken] = useState('')
  const [saved, setSaved] = useState(false)
  const [busy, setBusy] = useState(false)
  const [message, setMessage] = useState('Paste the token generated by claude setup-token. It is stored in this device\'s vault, and the app sends it, encrypted, to the environment of each repository you set up.')

  useEffect(() => {
    void githubTarget.read().then(setRepository)
    void agentCredentials.readClaude().then((value) => setSaved(Boolean(value)))
  }, [])

  async function save() {
    if (!token.trim()) return setMessage('Paste the Claude Code token to continue.')
    await agentCredentials.saveClaude(token.trim())
    setSaved(true)
    setMessage('Token saved on this device. It will be sent automatically when you set up agents in a repository.')
  }

  async function sendNow() {
    const [owner, repo] = repository.trim().split('/')
    if (!owner || !repo || repository.trim().split('/').length !== 2) return setMessage('Enter the repository as owner/repository.')
    const value = token.trim() || (await agentCredentials.readClaude())
    if (!value) return setMessage('Paste the Claude Code token to continue.')
    const github = await githubSession.read()
    if (!github) return setMessage('Connect GitHub before setting up Claude.')
    setBusy(true)
    try {
      await agentCredentials.saveClaude(value)
      setSaved(true)
      const env = await ensureAgentsEnvironment(github, `${owner}/${repo}`, await agentSettings.readAutomatic())
      await setEnvironmentSecret(github, env.repositoryId, AGENTS_ENVIRONMENT, 'CLAUDE_CODE_OAUTH_TOKEN', value)
      setToken('')
      setMessage(`Secret salvo no environment ${AGENTS_ENVIRONMENT} de ${repository.trim()}. ${env.message}`)
    } catch (error) {
      setMessage(error instanceof Error ? error.message : 'Could not set up the secret.')
    } finally {
      setBusy(false)
    }
  }

  async function forget() {
    await agentCredentials.clearClaude()
    setSaved(false)
    setMessage('Token removed from this device. Repositories already set up keep their copy.')
  }

  return <View style={styles.page}>
    <Text style={styles.title}>Set up Claude by subscription</Text>
    <Text style={styles.copy}>{message}</Text>
    <Text style={styles.status}>{saved ? 'Token saved on this device.' : 'No token saved.'}</Text>
    <TextInput value={token} onChangeText={setToken} autoCapitalize="none" secureTextEntry placeholder="Claude Code token" placeholderTextColor="#64748b" style={styles.input} />
    <Pressable disabled={busy} onPress={() => void save()} style={[styles.button, busy && styles.disabled]}><Text style={styles.buttonText}>Save on this device</Text></Pressable>
    <TextInput value={repository} onChangeText={setRepository} autoCapitalize="none" placeholder="owner/repository" placeholderTextColor="#64748b" style={styles.input} />
    <Pressable disabled={busy} onPress={() => void sendNow()} style={[styles.button, busy && styles.disabled]}>
      {busy ? <ActivityIndicator color="#fff" /> : <Text style={styles.buttonText}>Send to this repository now</Text>}
    </Pressable>
    {saved ? <Pressable onPress={() => void forget()} style={styles.secondary}><Text style={styles.buttonText}>Forget token on this device</Text></Pressable> : null}
  </View>
}

const styles = StyleSheet.create({
  page: { flex: 1, backgroundColor: '#101827', padding: 24, gap: 14 },
  title: { color: '#f8fafc', fontSize: 27, fontWeight: '700' },
  copy: { color: '#cbd5e1', fontSize: 15, lineHeight: 22 },
  status: { color: '#a7f3d0', fontSize: 13 },
  input: { color: '#f8fafc', backgroundColor: '#1e293b', borderRadius: 10, fontSize: 16, padding: 14 },
  button: { alignItems: 'center', backgroundColor: '#7c3aed', borderRadius: 10, minHeight: 48, justifyContent: 'center', padding: 12 },
  secondary: { alignItems: 'center', backgroundColor: '#475569', borderRadius: 10, minHeight: 44, justifyContent: 'center', padding: 10 },
  disabled: { opacity: 0.65 },
  buttonText: { color: '#fff', fontWeight: '700' }
})
